PAYMENT_METHOD_LABELS = {
    PaymentMethod.CASH: "cash",
    PaymentMethod.BANK_TRANSFER: "bank transfer",
    PaymentMethod.ESEWA: "eSewa",
    PaymentMethod.KHALTI: "Khalti",
    PaymentMethod.CHEQUE: "cheque",
}


def payment_method_label(method: PaymentMethod) -> str:
    return PAYMENT_METHOD_LABELS.get(method, _words(method.value))


def payment_received_message(
    *, amount: Decimal, method: PaymentMethod, invoice_number: str | None
) -> Message:
    towards = f" towards invoice {invoice_number}" if invoice_number else ""
    return Message(
        NotificationCategory.PAYMENT_RECEIVED,
        title=f"Payment received: {_npr(amount)}",
        body=(
            f"We have recorded your {payment_method_label(method)} payment "
            f"of {_npr(amount)}{towards}."
        ),
        link="/fees",
    )


