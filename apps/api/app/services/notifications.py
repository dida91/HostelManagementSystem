"""Notifications: the in-app inbox, and the email/SMS outbox behind it.

Callers describe WHAT happened with a Message; this module decides who gets it
on which channel. Notifications are written in the caller's transaction, and
delivery is queued only after that transaction commits.

Channel policy:
  * in-app    -- always
  * email     -- every message, when SMTP is configured and the user has an email
  * SMS       -- only messages that carry `sms` text (money and leave decisions),
                 when an SMS provider is configured and the user has a valid
                 Nepali mobile number. SMS costs money per message.

Every figure in a message (amounts, dates) comes from the database. Nothing
here is generated by a model -- see docs/adr/0003.
"""

